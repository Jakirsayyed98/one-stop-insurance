/**
 * Photo optimisation pipeline.
 *
 * Put original photos (JPG/PNG/WebP, ideally ≥1600px wide, licensed for commercial use) in
 * assets-src/photos/ using these names:
 *   hero.jpg          – homepage hero (landscape, ~4:3)
 *   two-wheeler.jpg   – two-wheeler category card
 *   private-car.jpg   – private car category card
 *   commercial.jpg    – commercial vehicle category card
 *
 * Then run:  npm run images
 * This creates AVIF + WebP + JPEG versions at several widths in public/images/photos/
 * and updates src/config/photos.ts so the site uses them (with width/height set to
 * prevent layout shift and lazy-loading below the fold). Remove a photo and re-run to
 * fall back to the built-in illustration.
 */
import sharp from 'sharp';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, parse } from 'node:path';

const SRC = 'assets-src/photos';
const OUT = 'public/images/photos';
const NAMES = ['hero', 'two-wheeler', 'private-car', 'commercial'] as const;
const WIDTHS = [480, 800, 1200, 1600];
const CROP: Record<string, [number, number]> = { hero: [4, 3], 'two-wheeler': [16, 9], 'private-car': [16, 9], commercial: [16, 9] };

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const files = existsSync(SRC) ? readdirSync(SRC).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)) : [];
const registry: Record<string, { width: number; height: number; widths: number[] }> = {};

for (const name of NAMES) {
  const file = files.find((f) => parse(f).name === name);
  if (!file) continue;
  const [rw, rh] = CROP[name];
  const meta = await sharp(join(SRC, file)).metadata();
  const maxW = Math.min(meta.width ?? 1600, 1600);
  const widths = WIDTHS.filter((w) => w <= maxW);
  if (!widths.length) widths.push(maxW);
  for (const w of widths) {
    const h = Math.round((w * rh) / rw);
    const base = sharp(join(SRC, file)).rotate().resize(w, h, { fit: 'cover', position: 'attention' });
    await base.clone().avif({ quality: 50, effort: 4 }).toFile(join(OUT, `${name}-${w}.avif`));
    await base.clone().webp({ quality: 74 }).toFile(join(OUT, `${name}-${w}.webp`));
    await base.clone().jpeg({ quality: 78, mozjpeg: true, progressive: true }).toFile(join(OUT, `${name}-${w}.jpg`));
  }
  const top = widths[widths.length - 1];
  registry[name] = { width: top, height: Math.round((top * rh) / rw), widths };
  console.log(`✔ ${name}: ${widths.join(', ')}px (AVIF, WebP, JPEG)`);
}

writeFileSync(
  'src/config/photos.ts',
  `/**
 * Responsive photo registry.
 * This file is (re)generated by \`npm run images\` from the originals in
 * assets-src/photos/. Do not edit by hand unless you know what you are doing.
 *
 * Supported names: hero, two-wheeler, private-car, commercial.
 * A missing entry means the site shows the built-in vehicle illustration instead.
 */
export type PhotoName = 'hero' | 'two-wheeler' | 'private-car' | 'commercial';

export const photos: Partial<Record<PhotoName, { width: number; height: number; widths: number[] }>> = ${JSON.stringify(registry, null, 2)};
`,
);
if (!Object.keys(registry).length) console.log('No photos found in assets-src/photos — illustrations will be used.');
